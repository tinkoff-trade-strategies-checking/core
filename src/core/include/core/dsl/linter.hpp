namespace core::dsl {

// Линтер магических констант (dsl.md, «Линтер магических констант», ФТ-13).
// L001 (уровень Warning) - на каждый числовой литерал внутри правила (условие,
// количество, цена, подстановка в `because`), кроме 0, 1 и 100. Диагностики
// идут в порядке текста. Исправление состоит из двух правок: вставка `param
// <имя> = <литерал>\n` в начало первой строки первого правила и замена литерала
// именем. Имя: аргумент функции f -> `f_n`; литерал сравнивается с вызовом f ->
// `f_level`; иначе `p1`, `p2`, ...; занятое имя получает суффикс `_2`, `_3`,
// ... Литералы в смещении `x[k]` не проверяются: смещение - часть записи ряда,
// а не уровень. Программа должна быть разобрана из `source`; чистая функция:
// без состояния и часов (INV-4).
std::vector<Diagnostic> lint(const Program &program, std::string_view source);

} // namespace core::dsl
